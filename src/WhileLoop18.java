public class WhileLoop18 {
    public static void main(String[] args) {
        System.out.println("This is the program to print number 1 to 10");
        int i=1;
        while (i<=10)
        {
            System.out.println(i);
            i++;
        }
        System.out.println("*************");
        int j=10;
        while (j>=1)
        {
            System.out.println(j);
            j--;
        }

    }
}
