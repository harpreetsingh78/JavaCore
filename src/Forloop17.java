public class Forloop17 {
    public static void main(String[] args) {
        System.out.println("This is a loop t print number 1 to 10");
        for (int i=1;i<=10;i++)
        {
            System.out.println(i);
        }
        System.out.println("*****************");
        for (int j=10;j>=1;j--)
        {
            System.out.println(j);
        }
    }
}
