public class SwitchCaseChar15 {
    public static void main(String[] args) {
        char var='A';
        switch (Character.toLowerCase(var)) {
            case 'a' -> System.out.println("This is case a");
            case 'b' -> System.out.println("This is case a");
            case 'c' -> System.out.println("This is case a");
            case 'd' -> System.out.println("This is case a");
            default -> System.out.println("Invalid Entry");



        }
    }
}
