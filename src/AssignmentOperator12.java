public class AssignmentOperator12 {
    public static void main(String[] args) {
        int x=5; //assigment operator =
        System.out.println(x+=4);//9
        System.out.println(x-=4);//5
        System.out.println(x*=4);//20
        System.out.println(x/=4);//5
        System.out.println(x%=4);//1
    }
}
